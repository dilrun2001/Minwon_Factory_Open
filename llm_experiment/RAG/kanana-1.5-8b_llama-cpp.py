from llama_cpp import Llama

minwon ="""안녕하세요.
부산시 사하구 낙동대로 457번안길 17 인근 도로변 하수구에서 최근 벌레(주로 작은 날벌레, 바퀴 등)가 다량으로 올라와 집 안으로 들어오는 상황이 지속되고 있습니다.

특히 환기를 위해 창문을 열어두면 벌레가 유입되어 위생상 불쾌하고, 생활에 큰 불편을 겪고 있습니다.
해당 구역 하수구의 방역 및 소독 조치를 요청드립니다.

필요하다면 인근 하수관로 전체에 대한 점검도 함께 부탁드립니다.

주민들이 쾌적하게 생활할 수 있도록 조속한 조치 부탁드립니다.

감사합니다."""

answer = """보건소에서는 월별 일정에 따라 관내 방역취약지를 분무소독 위주로 월 2~3회 정기적으로 방역하고있음, 요청한 지역은 10.19일 수요일에 살충방역했음"""

answer_format ="""1. 귀하의 가정에 행복이 가득하시길 바랍니다.

2. 귀하의 민원내용은 [민원요지]에 관한 것으로 이해(또는 판단) 됩니다.

3. 귀하의 질의사항에 대해 검토한 의견은 다음과 같습니다.

가. [답변내용]

4. 귀하의 질문에 만족스러운 답변이 되었기를 바라며, 답변 내용에 대한 추가 설명이 필요한 경우에는 사하구 [부서명]([이름], ☎[전화번호])에게 연락주시면 친절히 안내해 드리도록 하겠습니다.
감사합니다."""



system_prompt = """당신은 공공기관의 민원 응답을 담당하는 전문 공무원입니다.
기관 이름은 '사하구청'입니다.

다음의 **[답변 템플릿] 형식을 정확히 지켜서** 작성하십시오. 
⚠️ [답변 템플릿]의 형식을 **그대로 유지하고**, 출력 시작 부분이나 끝에 어떠한 추가 설명도 하지 마십시오.

※ 반드시 출력은 [답변 템플릿] 안에 있는 형식을 따르며, 템플릿 외 문장은 추가하지 마십시오.
※ 템플릿 내 `[민원요지]` 부분은 민원 내용을 행정 문서 문체로 정중하게 요약하여 대체하되, `[민원요지]`라는 단어는 최종 출력에 **표시되지 않아야 합니다**.
※ 템플릿 내 `[답변요지]` 부분은 답변 요지를 정중하고 행정적인 문체로 바꾸어 넣되, `[답변요지]`라는 단어는 최종 출력에 **표시되지 않아야 합니다**.
"""
user_prompt = """
다음은 민원에 대한 [답변 요지]와 [민원 내용]입니다.

[민원 내용]
""" + minwon + """

[답변 요지]
""" + answer + """

[답변 템플릿]
""" + answer_format


# 1. 다운받은 GGUF 모델 파일 로드
# n_gpu_layers=-1 : 가능한 모든 연산을 GPU에 맡기라는 뜻 (설정 안 되면 CPU가 빠르게 처리함)
llm = Llama(
    model_path="kanana-1.5-8b-instruct-2505-Q8_0.gguf",  # 아까 다운받은 파일 경로
    n_ctx=4096,                 # 문맥 길이
    n_gpu_layers=-1,             # GPU 사용 시도
    verbose=True
)

# 2. 질문하기
response = llm.create_chat_completion(
    messages=[
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt}
    ]
)

# 3. 답변 출력
print(response['choices'][0]['message']['content'])