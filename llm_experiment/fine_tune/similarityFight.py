from sentence_transformers import SentenceTransformer, util

# ✅ KURE-v1 모델 로드
model = SentenceTransformer("nlpai-lab/KURE-v1")

# ✅ 정답과 두 답변
reference = """1. 구정 행정에 관심을 가져주셔서 감사드립니다.

2. 귀하의 민원내용은 ①사하구 재난지원금 지급여부 및 지급계획, ②사하구 종교시설 재난방역지원금 지원에 대한 문의로 이해됩니다.

3. 귀하의 문의내용에 대하여 아래와 같이 답변드립니다.
가. 사하구 재난지원금 지급여부 및 지급계획 관련하여
- 현재 사상구는 2차 재난지원금, 남구는 3차 재난지원금을 지급하는 것으로 확인됩니다. 구 재난지원금은 구 자체재원으로 지급하고 있어 재정상황 등에 따라 지급시기, 지급금액 등이 상이할 수 있으며
- 사하구는 2021년 12월 초 신청·접수를 시작하여 올해 2월까지 사용할 수 있는 2차 재난지원금(사하구 일상회복지원금)을 선불카드 형태로 지급하였고 현재 3차 지원금 지급 계획은 없음을 알려드립니다.
나. 사하구 종교시설 재난방역지원금 지원 관련해서는
- 소상공인에 대하여는 ‘재난지원금’ 등 지원하고 있으나, 종교시설의 경우 비영리 법인의 성격, 영리 행위 제한에 따른 영업 손실 인정 곤란 등으로 대부분의 지원 대상에서 제외되고 있어, 방역지원(방역물품, 재난지원금 등)시 종교시설도 지원 대상에 포함될 수 있도록 적극 지원하도록 한 문화체육관광부 및 부산시의권고사항에 따라,
-「감염병의 예방 및 관리에 관한 법률」 제4조 2항에 근거하여 방역물품 구입 등으로 신청한 관내 종교시설에 한하여 5월 중 재난방역지원금을 지급할 예정입니다.

4. 답변 내용에 대해 추가 설명이 필요한 경우 [부서명] [이름]([전화번호]), [부서명] [이름]([전화번호])에게 연락주시면 친절히 안내해 드리겠습니다."""

answer1 = """1. 안녕하십니까? 귀하께서 신청하신 민원에 대한 검토결과를 다음과 같이 알려드립니다.

2. 귀하의 민원 내용은 사하구에서 재난지원금 지급 여부 및 종교시설에 대한 재난방역지원금 지급 여부에 관한 것으로 이해됩니다.

3. 귀하의 민원사항에 대해 검토한 결과는 다음과 같습니다.
가. 사하구 재난지원금 지급 여부 및 지급 계획에 대해 사상구와 남구에서는 각각 2차와 3차 재난지원금이 지급될 예정입니다. 반면, 사하구는 2차 재난지원금을 선불카드 형태로 이미 지급하였으며, 3차 지원금은 계획이 없습니다.

4. 귀하의 민원에 만족스러운 답변이 되었기를 바라며, 답변 내용에 대한 추가 설명이 필요한 경우 복지복지과([전화번호])으로 연락주시면 친절히 안내해 드리도록 하겠습니다. 감사합니다."""
answer2 = """1. 안녕하십니까? 귀하께서 신청하신 민원에 대한 검토결과를 다음과 같이 알려드립니다.

2. 귀하의 민원 내용은 사하구 재난지원금 지급여부 및 지급계획, 종교시설 재난방역지원금 지원에 관한 것으로 이해됩니다.

3. 귀하의 민원사항에 대해 검토한 결과는 다음과 같습니다.
가. 사하구 재난지원금 지급여부 및 지급계획: 사상구 2차, 남구 3차 재난지원금 지급, 사하구 2차 재난지원금 선불카드 형태로 지급, 3차 지원금 계획 없음.
나. 종교시설 재난방역지원금 지원: 종교시설 지원 대상 포함, 5월 중 방역물품 구입 지원.

4. 귀하의 민원에 만족스러운 답변이 되었기를 바라며, 답변 내용에 대한 추가 설명이 필요한 경우 [부서명]([이름], [전화번호])으로 연락주시면 친절히 안내해 드리도록 하겠습니다.
"""

# ✅ 임베딩 생성
sentences = [reference, answer1, answer2]
embeddings = model.encode(sentences)

# ✅ 유사도 계산 (정답 vs 각각의 답변)
sim1 = util.cos_sim(embeddings[0], embeddings[1]).item()
sim2 = util.cos_sim(embeddings[0], embeddings[2]).item()

# ✅ 결과 출력
print("🧾 기준 답변:", reference)
print("📝 답변 1:", answer1)
print("📝 답변 2:", answer2)
print("\n✅ 유사도 결과:")
print(f"정답 vs 답변 1: {sim1:.4f}")
print(f"정답 vs 답변 2: {sim2:.4f}")